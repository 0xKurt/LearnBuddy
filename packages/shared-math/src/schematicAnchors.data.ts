// Where the parts of the picture library's images stand (issue #599): per part the point on the
// motif its leader line starts at (`at`), where its number stands (`badge`, in a column at x = 12
// or x = 288; in a row picture in its cell's corner) and the area a finger hits (`tap`, [x, y,
// width, height], at least 44 × 44 — a row picture's whole cell). `tap: null`: the part is named
// only — its structure is larger than a tap area, is drawn more than once (both lungs, every
// myelin segment) or continues elsewhere (the colon), or its anchor stands too close to the next;
// a tap on it would be recorded as nothing or as a neighbour, so no question asks to tap it and no
// finger can pick it (each with its reason in docs/adr/0009). One coordinate system for all:
// the image's frame 300 wide (`SCHEMATIC_IMAGE_WIDTH`), as high as `schematicFrame` says, origin
// top left — the system of the design package's `assets/figures/anchors/<id>.json`, from which
// this file was taken. The parts stand in the order of their names (`schematics.data.ts`); a part
// the image does not show has neither a name nor an anchor
// (apps/mobile/assets/figures/TEILE.md, column "Fällt weg").
//
// This file is the source from here on: every anchor was looked at on its image, and those that
// stood beside the named structure were moved onto it (the list, old → new, is in
// docs/adr/0009-labelled-pictures-are-images.md). A changed image needs its anchors looked at
// again. Held to the names, the frames and the 44 × 44 by `__tests__/schematicAnchors.test.ts`
// and, with zod, by apps/api/src/modules/practice/__tests__/schematicCheck.test.ts.
//
// The server reads it for what a finger can tap; the app loads it with the first picture
// (`useSchematicPictures`), so it is no part of the start bundle.

